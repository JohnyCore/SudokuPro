"""The "Special" palettes: fourteen apps people already spend their day in.

A player who lives in Discord or VS Code or Spotify wants the tool they solved
the Sudoku in to look like the tool they spend the day in. These are not
"inspired by" those apps -- they use the colours those apps actually use, so
recognising one is instant.

Each palette keeps the app's three *signals*: its background, its panel colour
and its accent. It does not get to have its own digit colours. A player's own
digits are blue and a wrong digit is red in every palette in the app, and a
palette that broke that rule would make a mistake on a Spotify board mean
something different from a mistake anywhere else. That is why Spotify is black
and green everywhere except the digits.

Three of the fourteen are light and eleven are dark, which is how those apps
actually ship: Discord, VS Code, Spotify, Steam, Obsidian, Brave, GitHub, TikTok,
Reddit, YouTube and Windows 11 are dark by default, while WhatsApp, Telegram and
Duolingo are light. Each one is registered in the mode it belongs to, so picking
it switches dark mode the same way any other palette does.
"""

